"""
PREPRIA — Interview Performance Report PDF Generation Service
Generates authoritative, production-grade PDF evaluation reports from persisted interview session data.
Zero-DOM scraping, zero-browser dependency, fully deterministic and secure.
"""

import io
import re
from typing import Dict, Any, List, Optional
from datetime import datetime


def _sanitize_pdf_text(text: Any) -> str:
    """Sanitizes text for standard PDF Type 1 fonts (Helvetica/Times)."""
    if text is None:
        return ""
    s = str(text)
    # Replace common Unicode quotes and dashes with ASCII equivalents
    replacements = {
        "\u2018": "'",
        "\u2019": "'",
        "\u201c": '"',
        "\u201d": '"',
        "\u2013": "-",
        "\u2014": "--",
        "\u2026": "...",
        "\u2022": "*",
        "\u00a0": " ",
        "\u2713": "✓",
        "\u2714": "✓",
    }
    for orig, repl in replacements.items():
        s = s.replace(orig, repl)
    # Encode to latin-1 safe representation
    clean_chars = []
    for ch in s:
        if ord(ch) < 128:
            clean_chars.append(ch)
        elif ord(ch) < 256:
            clean_chars.append(ch)
        else:
            clean_chars.append("?")
    return "".join(clean_chars)


def _escape_pdf_literal(text: str) -> str:
    """Escapes parentheses and backslashes for PDF string literals (text)."""
    return text.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")


def _wrap_text(text: str, max_chars_per_line: int) -> List[str]:
    """Wraps text into lines not exceeding max_chars_per_line."""
    if not text:
        return []
    words = text.split()
    lines = []
    current_line = []
    current_len = 0

    for word in words:
        w_len = len(word)
        if current_line and (current_len + w_len + 1 > max_chars_per_line):
            lines.append(" ".join(current_line))
            current_line = [word]
            current_len = w_len
        else:
            current_line.append(word)
            current_len += w_len + (1 if len(current_line) > 1 else 0)

    if current_line:
        lines.append(" ".join(current_line))
    return lines


class SimplePDFCanvas:
    """Lightweight, deterministic PDF generator supporting multi-page layout, tables, and styling."""

    def __init__(self, page_width: float = 595.28, page_height: float = 841.89):
        # A4: 595.28 x 841.89 pt
        self.page_width = page_width
        self.page_height = page_height
        self.margin_left = 40.0
        self.margin_right = 40.0
        self.margin_top = 45.0
        self.margin_bottom = 45.0
        self.content_width = page_width - self.margin_left - self.margin_right

        self.pages: List[List[str]] = []
        self.current_page_stream: List[str] = []
        self.cursor_y = self.page_height - self.margin_top
        self.page_number = 1

    def _start_new_page(self):
        """Finalizes the current page and starts a fresh one."""
        if self.current_page_stream:
            self._draw_page_decorations()
            self.pages.append(self.current_page_stream)
            self.current_page_stream = []
            self.page_number += 1
            self.cursor_y = self.page_height - self.margin_top

    def ensure_space(self, height_needed: float):
        """If remaining vertical space is less than height_needed, triggers a page break."""
        if (self.cursor_y - height_needed) < self.margin_bottom:
            self._start_new_page()

    def _draw_page_decorations(self):
        """Draws top brand line and footer with page number."""
        # Top brand accent bar
        self.current_page_stream.append("q")
        self.current_page_stream.append("0.914 0.471 0.384 rg") # Coral/Primary #E97862
        self.current_page_stream.append(f"{self.margin_left} {self.page_height - 25} {self.content_width} 3 re f")
        
        # Header text
        self.current_page_stream.append("0.4 0.4 0.4 rg")
        self.current_page_stream.append("BT")
        self.current_page_stream.append("/F1 8 Tf")
        self.current_page_stream.append(f"{self.margin_left} {self.page_height - 35} Td")
        self.current_page_stream.append("(PREPRIA AI CAREER READINESS -- INTERVIEW PERFORMANCE REPORT) Tj")
        self.current_page_stream.append("ET")

        # Footer text & page number
        self.current_page_stream.append("0.5 0.5 0.5 rg")
        self.current_page_stream.append("BT")
        self.current_page_stream.append("/F1 8 Tf")
        self.current_page_stream.append(f"{self.margin_left} {self.margin_bottom - 20} Td")
        self.current_page_stream.append("(Confidential Candidate Assessment -- Generated by PREPRIA Engine) Tj")
        self.current_page_stream.append("ET")

        page_str = f"Page {self.page_number}"
        self.current_page_stream.append("BT")
        self.current_page_stream.append("/F1 8 Tf")
        self.current_page_stream.append(f"{self.page_width - self.margin_right - 40} {self.margin_bottom - 20} Td")
        self.current_page_stream.append(f"({page_str}) Tj")
        self.current_page_stream.append("ET")
        self.current_page_stream.append("Q")

    def draw_heading_1(self, text: str):
        """Renders Level 1 Title Heading."""
        self.ensure_space(35)
        clean = _escape_pdf_literal(_sanitize_pdf_text(text))
        self.current_page_stream.append("q")
        self.current_page_stream.append("0.1 0.12 0.15 rg") # Dark slate
        self.current_page_stream.append("BT")
        self.current_page_stream.append("/F2 18 Tf") # Bold
        self.current_page_stream.append(f"{self.margin_left} {self.cursor_y - 18} Td")
        self.current_page_stream.append(f"({clean}) Tj")
        self.current_page_stream.append("ET")
        self.current_page_stream.append("Q")
        self.cursor_y -= 28

    def draw_heading_2(self, text: str):
        """Renders Level 2 Section Heading with background pill."""
        self.ensure_space(30)
        clean = _escape_pdf_literal(_sanitize_pdf_text(text))
        
        # Section background pill
        self.current_page_stream.append("q")
        self.current_page_stream.append("0.96 0.97 0.98 rg") # Light background
        self.current_page_stream.append(f"{self.margin_left} {self.cursor_y - 20} {self.content_width} 22 re f")
        self.current_page_stream.append("0.914 0.471 0.384 rg") # Left accent indicator
        self.current_page_stream.append(f"{self.margin_left} {self.cursor_y - 20} 3.5 22 re f")

        self.current_page_stream.append("0.1 0.15 0.2 rg")
        self.current_page_stream.append("BT")
        self.current_page_stream.append("/F2 11 Tf")
        self.current_page_stream.append(f"{self.margin_left + 10} {self.cursor_y - 15} Td")
        self.current_page_stream.append(f"({clean}) Tj")
        self.current_page_stream.append("ET")
        self.current_page_stream.append("Q")
        self.cursor_y -= 30

    def draw_text_paragraph(self, text: str, font_size: float = 9.0, is_bold: bool = False, color: str = "0.2 0.2 0.2", indent: float = 0.0):
        """Renders a paragraph with line wrapping."""
        if not text:
            return
        clean = _sanitize_pdf_text(text)
        max_chars = int((self.content_width - indent) / (font_size * 0.52))
        lines = _wrap_text(clean, max_chars)
        line_height = font_size * 1.35

        self.ensure_space(len(lines) * line_height + 4)

        font_name = "/F2" if is_bold else "/F1"
        self.current_page_stream.append("q")
        self.current_page_stream.append(f"{color} rg")
        self.current_page_stream.append("BT")
        self.current_page_stream.append(f"{font_name} {font_size} Tf")

        first = True
        for line in lines:
            esc = _escape_pdf_literal(line)
            if first:
                self.current_page_stream.append(f"{self.margin_left + indent} {self.cursor_y - font_size} Td")
                first = False
            else:
                self.current_page_stream.append(f"0 -{line_height} Td")
            self.current_page_stream.append(f"({esc}) Tj")
            self.cursor_y -= line_height

        self.current_page_stream.append("ET")
        self.current_page_stream.append("Q")
        self.cursor_y -= 4

    def draw_key_value_grid(self, pairs: List[tuple], columns: int = 2):
        """Renders structured key-value metadata cards in a grid."""
        row_height = 22.0
        col_width = self.content_width / columns
        total_rows = (len(pairs) + columns - 1) // columns
        needed_height = total_rows * row_height + 6

        self.ensure_space(needed_height)

        for idx, (label, val) in enumerate(pairs):
            col_idx = idx % columns
            row_idx = idx // columns
            x_pos = self.margin_left + (col_idx * col_width)
            y_pos = self.cursor_y - (row_idx * row_height) - 15

            lbl_esc = _escape_pdf_literal(_sanitize_pdf_text(label))
            val_esc = _escape_pdf_literal(_sanitize_pdf_text(val))

            self.current_page_stream.append("q")
            # Label
            self.current_page_stream.append("0.45 0.45 0.45 rg")
            self.current_page_stream.append("BT")
            self.current_page_stream.append("/F2 8.5 Tf")
            self.current_page_stream.append(f"{x_pos} {y_pos} Td")
            self.current_page_stream.append(f"({lbl_esc}:) Tj")
            self.current_page_stream.append("ET")

            # Value
            self.current_page_stream.append("0.1 0.1 0.1 rg")
            self.current_page_stream.append("BT")
            self.current_page_stream.append("/F1 8.5 Tf")
            self.current_page_stream.append(f"{x_pos + 85} {y_pos} Td")
            self.current_page_stream.append(f"({val_esc}) Tj")
            self.current_page_stream.append("ET")
            self.current_page_stream.append("Q")

        self.cursor_y -= needed_height

    def draw_pillar_scorecards(self, dimensions: Dict[str, Any], overall_score: int):
        """Renders 5-Pillar Scorecard cards with progress visuals."""
        card_height = 50.0
        self.ensure_space(card_height + 30)

        # Main overall score highlight
        self.current_page_stream.append("q")
        self.current_page_stream.append("0.98 0.95 0.94 rg") # Warm light background
        self.current_page_stream.append("0.914 0.471 0.384 RG") # Primary border
        self.current_page_stream.append("1 w")
        self.current_page_stream.append(f"{self.margin_left} {self.cursor_y - 42} {self.content_width} 42 re b")

        self.current_page_stream.append("0.914 0.471 0.384 rg")
        self.current_page_stream.append("BT")
        self.current_page_stream.append("/F2 22 Tf")
        self.current_page_stream.append(f"{self.margin_left + 15} {self.cursor_y - 30} Td")
        self.current_page_stream.append(f"({overall_score}%) Tj")
        self.current_page_stream.append("ET")

        status_text = "STRONG CANDIDATE (Readiness >= 75%)" if overall_score >= 75 else "DEVELOPING CANDIDATE"
        self.current_page_stream.append("0.2 0.2 0.2 rg")
        self.current_page_stream.append("BT")
        self.current_page_stream.append("/F2 11 Tf")
        self.current_page_stream.append(f"{self.margin_left + 80} {self.cursor_y - 23} Td")
        self.current_page_stream.append(f"({_escape_pdf_literal(status_text)}) Tj")
        self.current_page_stream.append("ET")

        self.current_page_stream.append("0.45 0.45 0.45 rg")
        self.current_page_stream.append("BT")
        self.current_page_stream.append("/F1 8.5 Tf")
        self.current_page_stream.append(f"{self.margin_left + 80} {self.cursor_y - 35} Td")
        self.current_page_stream.append("(Weighted composite across Technical, Problem Solving, Communication, Role, and Confidence) Tj")
        self.current_page_stream.append("ET")
        self.current_page_stream.append("Q")

        self.cursor_y -= 52

        # 5 Pillar Cards in a Row
        pillars = [
            ("Technical", dimensions.get("technicalKnowledge", 0)),
            ("Problem Solving", dimensions.get("problemSolving", 0)),
            ("Communication", dimensions.get("communication", 0)),
            ("Role Knowledge", dimensions.get("roleKnowledge", 0)),
            ("Confidence", dimensions.get("confidence", 0)),
        ]
        card_w = (self.content_width - 20) / 5.0
        p_height = 42.0
        self.ensure_space(p_height + 10)

        for i, (name, sc) in enumerate(pillars):
            cx = self.margin_left + i * (card_w + 5)
            cy = self.cursor_y - p_height

            self.current_page_stream.append("q")
            self.current_page_stream.append("0.96 0.97 0.98 rg")
            self.current_page_stream.append("0.85 0.88 0.91 RG")
            self.current_page_stream.append("0.75 w")
            self.current_page_stream.append(f"{cx} {cy} {card_w} {p_height} re b")

            # Score number
            self.current_page_stream.append("0.1 0.15 0.2 rg")
            self.current_page_stream.append("BT")
            self.current_page_stream.append("/F2 13 Tf")
            self.current_page_stream.append(f"{cx + 8} {cy + 24} Td")
            self.current_page_stream.append(f"({sc}%) Tj")
            self.current_page_stream.append("ET")

            # Pillar name
            self.current_page_stream.append("0.4 0.45 0.5 rg")
            self.current_page_stream.append("BT")
            self.current_page_stream.append("/F1 7.5 Tf")
            self.current_page_stream.append(f"{cx + 8} {cy + 10} Td")
            self.current_page_stream.append(f"({_escape_pdf_literal(name)}) Tj")
            self.current_page_stream.append("ET")
            self.current_page_stream.append("Q")

        self.cursor_y -= (p_height + 14)

    def draw_callout_box(self, title: str, text: str, bg_rgb: str = "0.95 0.97 1.0", border_rgb: str = "0.7 0.8 0.95", text_rgb: str = "0.1 0.2 0.4"):
        """Renders an alert / callout box with wrapped text."""
        clean_text = _sanitize_pdf_text(text)
        lines = _wrap_text(clean_text, int(self.content_width / 4.8))
        line_height = 11.0
        box_height = len(lines) * line_height + 24.0

        self.ensure_space(box_height + 6)
        cy = self.cursor_y - box_height

        self.current_page_stream.append("q")
        self.current_page_stream.append(f"{bg_rgb} rg")
        self.current_page_stream.append(f"{border_rgb} RG")
        self.current_page_stream.append("0.75 w")
        self.current_page_stream.append(f"{self.margin_left} {cy} {self.content_width} {box_height} re b")

        # Title
        if title:
            self.current_page_stream.append(f"{text_rgb} rg")
            self.current_page_stream.append("BT")
            self.current_page_stream.append("/F2 9 Tf")
            self.current_page_stream.append(f"{self.margin_left + 10} {cy + box_height - 14} Td")
            self.current_page_stream.append(f"({_escape_pdf_literal(_sanitize_pdf_text(title))}) Tj")
            self.current_page_stream.append("ET")

        # Lines
        self.current_page_stream.append("0.2 0.25 0.3 rg")
        self.current_page_stream.append("BT")
        self.current_page_stream.append("/F1 8.5 Tf")
        start_y = cy + box_height - (24 if title else 14)
        first = True
        for line in lines:
            esc = _escape_pdf_literal(line)
            if first:
                self.current_page_stream.append(f"{self.margin_left + 10} {start_y} Td")
                first = False
            else:
                self.current_page_stream.append(f"0 -{line_height} Td")
            self.current_page_stream.append(f"({esc}) Tj")

        self.current_page_stream.append("ET")
        self.current_page_stream.append("Q")

        self.cursor_y -= (box_height + 10)

    def draw_divider(self):
        """Draws a subtle horizontal divider line."""
        self.ensure_space(10)
        self.current_page_stream.append("q")
        self.current_page_stream.append("0.88 0.9 0.92 RG")
        self.current_page_stream.append("0.5 w")
        self.current_page_stream.append(f"{self.margin_left} {self.cursor_y - 4} m {self.page_width - self.margin_right} {self.cursor_y - 4} l S")
        self.current_page_stream.append("Q")
        self.cursor_y -= 12

    def build_pdf_bytes(self) -> bytes:
        """Finalizes all pages and compiles the complete PDF binary payload."""
        # Finalize the last active page
        if self.current_page_stream:
            self._draw_page_decorations()
            self.pages.append(self.current_page_stream)
            self.current_page_stream = []

        total_pages = len(self.pages)
        if total_pages == 0:
            self._draw_page_decorations()
            self.pages.append(["BT /F1 10 Tf 50 750 Td (No Evaluation Content) Tj ET"])
            total_pages = 1

        out = io.BytesIO()
        out.write(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")

        offsets = []
        obj_id = 1

        # Object 1: Catalog
        offsets.append(out.tell())
        out.write(f"{obj_id} 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n".encode("latin-1"))
        obj_id += 1

        # Object 2: Pages (Kids placeholder)
        pages_obj_id = 2
        page_obj_ids = []
        for i in range(total_pages):
            page_obj_ids.append(obj_id + i * 2) # Page objects will take obj_id, obj_id+2, etc.

        offsets.append(out.tell())
        kids_str = " ".join(f"{pid} 0 R" for pid in page_obj_ids)
        out.write(f"{pages_obj_id} 0 obj\n<< /Type /Pages /Kids [{kids_str}] /Count {total_pages} >>\nendobj\n".encode("latin-1"))
        obj_id += 1

        # Fonts Objects
        f1_id = obj_id
        offsets.append(out.tell())
        out.write(f"{f1_id} 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>\nendobj\n".encode("latin-1"))
        obj_id += 1

        f2_id = obj_id
        offsets.append(out.tell())
        out.write(f"{f2_id} 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>\nendobj\n".encode("latin-1"))
        obj_id += 1

        # Create Page & Content Stream objects for each page
        for p_idx, stream_lines in enumerate(self.pages):
            p_obj_id = obj_id
            c_obj_id = obj_id + 1
            obj_id += 2

            content_data = "\n".join(stream_lines).encode("latin-1", errors="replace")
            c_len = len(content_data)

            # Page Object
            offsets.append(out.tell())
            out.write(
                f"{p_obj_id} 0 obj\n<< /Type /Page /Parent {pages_obj_id} 0 R "
                f"/MediaBox [0 0 {self.page_width:.2f} {self.page_height:.2f}] "
                f"/Contents {c_obj_id} 0 R "
                f"/Resources << /Font << /F1 {f1_id} 0 R /F2 {f2_id} 0 R >> >> >>\nendobj\n".encode("latin-1")
            )

            # Content Stream Object
            offsets.append(out.tell())
            out.write(
                f"{c_obj_id} 0 obj\n<< /Length {c_len} >>\nstream\n".encode("latin-1")
            )
            out.write(content_data)
            out.write(b"\nendstream\nendobj\n")

        # Cross-reference Table (xref)
        xref_offset = out.tell()
        total_objects = obj_id
        out.write(f"xref\n0 {total_objects}\n".encode("latin-1"))
        out.write(b"0000000000 65535 f \n")
        for off in offsets:
            out.write(f"{off:010d} 00000 n \n".encode("latin-1"))

        # Trailer
        out.write(
            f"trailer\n<< /Size {total_objects} /Root 1 0 R >>\n"
            f"startxref\n{xref_offset}\n%%EOF\n".encode("latin-1")
        )

        return out.getvalue()


def generate_interview_pdf_report(session: Dict[str, Any], user_identity: Optional[str] = None) -> bytes:
    """
    Generates a complete, authoritative PDF evaluation report for a candidate interview session.
    Extracts all fields directly from persisted session evaluation data.
    """
    canvas = SimplePDFCanvas()

    # 1. Header Information
    role_name = session.get("roleName") or session.get("role") or "Software Engineering Candidate"
    difficulty = session.get("difficulty") or "Intermediate"
    interview_type = session.get("interviewType") or "Technical"
    duration = session.get("duration") or "N/A"
    completed_at = session.get("completedAt") or session.get("timestamp") or datetime.utcnow().strftime("%b %d, %Y")
    answered_count = session.get("answeredCount", 0)
    total_q = session.get("questionCount") or session.get("totalQuestions") or len(session.get("questionEvaluations", []))
    status_label = session.get("status") or "completed"
    violations_count = session.get("violationsCount", 0)

    canvas.draw_heading_1(f"Interview Evaluation: {role_name}")

    # Metadata Grid
    metadata_pairs = [
        ("Target Role", role_name),
        ("Difficulty Level", difficulty),
        ("Interview Type", interview_type),
        ("Session Date", completed_at),
        ("Elapsed Duration", duration),
        ("Questions Answered", f"{answered_count} of {total_q}"),
        ("Proctoring Warnings", f"{violations_count} warning(s)"),
        ("Session Status", status_label.replace("_", " ").title()),
    ]
    canvas.draw_key_value_grid(metadata_pairs, columns=2)
    canvas.draw_divider()

    # 2. Overall Performance & 5-Pillar Scores
    canvas.draw_heading_2("1. Overall Score & 5-Pillar Competency Breakdown")
    raw_score = session.get("overallScore") if session.get("overallScore") is not None else session.get("score", 0)
    score_val = int(raw_score * 100) if (isinstance(raw_score, float) and 0 < raw_score <= 1.0) else int(raw_score or 0)
    dimensions = session.get("dimensions") or {
        "technicalKnowledge": score_val,
        "problemSolving": score_val,
        "communication": session.get("fluency_score", score_val),
        "roleKnowledge": score_val,
        "confidence": int((session.get("emotion_confidence", 0.75) * 100) if isinstance(session.get("emotion_confidence"), float) and session.get("emotion_confidence") <= 1.0 else 75)
    }
    canvas.draw_pillar_scorecards(dimensions, score_val)

    # 3. Speech Quality & Acoustic Metrics (Phase 14)
    canvas.draw_heading_2("2. Speech Quality & Verbal Delivery Analysis")
    speech_metrics = session.get("speech_metrics") or {}
    total_fillers = speech_metrics.get("total_filler_count", 0)
    filler_rate = speech_metrics.get("filler_rate")
    wpm = speech_metrics.get("words_per_minute")
    breakdown = speech_metrics.get("filler_breakdown") or {}
    observations = speech_metrics.get("speech_observations") or []

    speech_pairs = [
        ("Total Filler Words", str(total_fillers)),
        ("Filler Frequency", f"{filler_rate} per 100 words" if filler_rate is not None else "Not available"),
        ("Speaking Rate (WPM)", f"{wpm} WPM" if wpm is not None else "Not available (duration not captured)"),
        ("Verbal Fluency Score", f"{dimensions.get('communication', 80)}% Benchmark"),
    ]
    canvas.draw_key_value_grid(speech_pairs, columns=2)

    # Filler breakdown detail
    if total_fillers == 0:
        canvas.draw_callout_box(
            title="Verbal Clarity Assessment",
            text="No filler words detected throughout your interview responses. Excellent verbal clarity and pacing.",
            bg_rgb="0.94 0.98 0.95",
            border_rgb="0.6 0.85 0.65",
            text_rgb="0.1 0.4 0.15"
        )
    else:
        breakdown_text = ", ".join([f'"{w}": {cnt} time(s)' for w, cnt in breakdown.items()])
        canvas.draw_callout_box(
            title="Detected Filler-Word Breakdown",
            text=f"Detected occurrences: {breakdown_text}",
            bg_rgb="0.99 0.96 0.93",
            border_rgb="0.95 0.75 0.6",
            text_rgb="0.5 0.25 0.1"
        )

    # Speech Observations
    for obs in observations:
        canvas.draw_text_paragraph(f"- {obs}", font_size=8.5, indent=5.0, color="0.2 0.3 0.45")

    canvas.draw_divider()

    # 4. Question-by-Question Response Audit
    canvas.draw_heading_2("3. Question-by-Question Response Audit")
    q_evals = session.get("questionEvaluations") or []

    if not q_evals:
        canvas.draw_text_paragraph("No detailed question evaluations recorded for this session.", font_size=8.5)
    else:
        for idx, qe in enumerate(q_evals):
            q_num = qe.get("questionIndex") or (idx + 1)
            q_text = qe.get("question") or f"Question {q_num}"
            q_topic = qe.get("topic") or "General"
            q_score = qe.get("score", 0)
            q_status = qe.get("status") or "answered"
            q_star = qe.get("hasSTARStructure", False)
            q_ans = qe.get("answerText") or qe.get("answer") or "[No Answer Recorded]"
            q_sp = qe.get("speech_analysis") or {}

            canvas.ensure_space(60)

            # Question Title & Status Header
            canvas.draw_text_paragraph(
                f"Q{q_num}: {q_text} ({q_topic} | Score: {q_score}% | {q_status.upper()})",
                font_size=9.5,
                is_bold=True,
                color="0.1 0.15 0.25"
            )

            # Candidate Transcript
            canvas.draw_callout_box(
                title="Candidate Response Transcript",
                text=q_ans,
                bg_rgb="0.98 0.98 0.99",
                border_rgb="0.88 0.9 0.92",
                text_rgb="0.25 0.25 0.3"
            )

            # Question speech metadata & STAR
            sp_details = []
            if q_star:
                sp_details.append("STAR Alignment: Detected")
            f_count = q_sp.get("filler_count", 0)
            if f_count > 0:
                sp_details.append(f"Fillers: {f_count}")
            if q_sp.get("wpm"):
                sp_details.append(f"Pace: {q_sp.get('wpm')} WPM")
            if qe.get("wordCount"):
                sp_details.append(f"Word Count: {qe.get('wordCount')} words")

            if sp_details:
                canvas.draw_text_paragraph(" | ".join(sp_details), font_size=7.5, color="0.45 0.45 0.5", indent=5.0)

            canvas.cursor_y -= 4

    canvas.draw_divider()

    # 5. Strengths & Recommended Improvements
    canvas.draw_heading_2("4. Strengths & Recommended Next Steps")

    strengths = session.get("strengths") or ["Demonstrated functional baseline understanding across core role competencies."]
    canvas.draw_text_paragraph("Identified Key Strengths:", font_size=9.0, is_bold=True, color="0.1 0.4 0.2")
    for s in strengths:
        canvas.draw_text_paragraph(f"- {s}", font_size=8.5, indent=8.0, color="0.15 0.35 0.2")

    canvas.cursor_y -= 6

    improvements = session.get("improvements") or []
    if improvements:
        canvas.draw_text_paragraph("Targeted Improvement Areas:", font_size=9.0, is_bold=True, color="0.6 0.3 0.1")
        for imp in improvements:
            if isinstance(imp, dict):
                top = imp.get("topic", "Focus Area")
                desc = imp.get("description", "")
                canvas.draw_text_paragraph(f"- {top}: {desc}", font_size=8.5, indent=8.0, color="0.3 0.25 0.2")
            else:
                canvas.draw_text_paragraph(f"- {imp}", font_size=8.5, indent=8.0, color="0.3 0.25 0.2")

    # 6. Proctoring & Verification Statement
    if violations_count > 0 or status_label == "terminated_for_violations":
        canvas.draw_divider()
        canvas.draw_heading_2("5. Proctoring & Academic Integrity Audit")
        proc_status = f"Session recorded {violations_count} proctoring warning(s)."
        if status_label == "terminated_for_violations":
            proc_status += " The interview was terminated early due to exceeding maximum allowed integrity warnings."
        canvas.draw_callout_box(
            title="Integrity Record",
            text=proc_status,
            bg_rgb="0.99 0.94 0.94",
            border_rgb="0.95 0.7 0.7",
            text_rgb="0.6 0.1 0.1"
        )

    return canvas.build_pdf_bytes()
